'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const {
  GENERATED_RUNTIME_BUNDLE,
  buildRuntimeBundleSource
} = require('./build-apps-script-runtime-bundle');

const POLICY_VERSION = 'apps-script-top-level-v3';
const BUILD_INFO_SCHEMA_VERSION = 1;
const GENERATED_BUILD_INFO = 'BuildInfo.js';
const RUNTIME_BUNDLE_MARKER = 'r2-runtime-bundle.json';
const RUNTIME_BUNDLE_MARKER_SCHEMA = 'PRH_R2_RUNTIME_BUNDLE_MARKER_V1';
const ECHARTS_VENDOR_MARKER = 'echarts-vendor.json';
const ECHARTS_VENDOR_SCHEMA = 'PRH_ECHARTS_VENDOR_LOCK_V1';
const ECHARTS_VENDOR_PLACEHOLDER = '<!-- PRH_LOCAL_ECHARTS_VENDOR -->';
const ECHARTS_TARGET_HTML = 'FinancialHomeWebApp.html';
const SHA_RE = /^[0-9a-f]{40}$/;

function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

function gitBlobSha1(buffer) {
  const bytes = Buffer.isBuffer(buffer) ? buffer : Buffer.from(buffer);
  return crypto.createHash('sha1')
    .update(Buffer.from(`blob ${bytes.length}\0`, 'utf8'))
    .update(bytes)
    .digest('hex');
}

function parseArgs(argv) {
  const result = {};
  for (let i = 2; i < argv.length; i += 2) {
    const key = argv[i];
    const value = argv[i + 1];
    if (!key || !key.startsWith('--') || value == null) throw new Error('usage: --source <dir> --out <dir> --sha <40-char-sha> [--repository-root <dir>]');
    result[key.slice(2)] = value;
  }
  return result;
}

function listDeployFiles(sourceRoot) {
  const entries = fs.readdirSync(sourceRoot, { withFileTypes: true });
  for (const reserved of [GENERATED_BUILD_INFO, GENERATED_RUNTIME_BUNDLE]) {
    if (entries.some((entry) => entry.name === reserved)) {
      throw new Error(`${reserved} is reserved for deterministic build output`);
    }
  }
  const files = entries
    .filter((entry) => entry.isFile() && (entry.name === 'appsscript.json' || entry.name.endsWith('.js') || entry.name.endsWith('.html')))
    .map((entry) => entry.name)
    .sort();
  if (!files.includes('appsscript.json')) throw new Error('appsscript.json is required');
  if (!files.some((name) => name.endsWith('.js'))) throw new Error('at least one Apps Script .js file is required');
  return files;
}

function stableFileSetHash(files) {
  const payload = files.map((item) => `${item.path}\0${item.sha256}\0${item.size}`).join('\n');
  return sha256(Buffer.from(payload, 'utf8'));
}

function buildInfoSource(candidateSha, sourceTreeHash) {
  return [
    '/** Generated by trusted candidate packager. Do not edit or commit. */',
    'var PR_BUILD_INFO = Object.freeze(' + JSON.stringify({
      schemaVersion: BUILD_INFO_SCHEMA_VERSION,
      candidateSha,
      sourceTreeHash,
      policyVersion: POLICY_VERSION
    }) + ');',
    ''
  ].join('\n');
}

function sourceFileDescriptors(source, names) {
  return names.map((name) => {
    const sourcePath = path.join(source, name);
    const stat = fs.lstatSync(sourcePath);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`deploy file must be a regular file: ${name}`);
    const bytes = fs.readFileSync(sourcePath);
    return { path: name, sha256: sha256(bytes), size: bytes.length, bytes };
  });
}

function descriptorFromGenerated(pathName, sourceText) {
  const bytes = Buffer.from(sourceText, 'utf8');
  return { path: pathName, sha256: sha256(bytes), size: bytes.length, bytes };
}

function runtimeBundleConfig(sourceRoot) {
  const markerPath = path.join(sourceRoot, RUNTIME_BUNDLE_MARKER);
  if (!fs.existsSync(markerPath)) return Object.freeze({ enabled: false, marker: null });
  const stat = fs.lstatSync(markerPath);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error('runtime bundle marker must be a regular file');
  const marker = JSON.parse(fs.readFileSync(markerPath, 'utf8'));
  if (!marker || marker.schema !== RUNTIME_BUNDLE_MARKER_SCHEMA || marker.version !== '1.0.0' || marker.enabled !== true) {
    throw new Error('runtime bundle marker is invalid');
  }
  return Object.freeze({ enabled: true, marker: Object.freeze({ schema: marker.schema, version: marker.version }) });
}

function echartsVendorConfig(sourceRoot) {
  const markerPath = path.join(sourceRoot, ECHARTS_VENDOR_MARKER);
  if (!fs.existsSync(markerPath)) return Object.freeze({ enabled: false, marker: null });
  const stat = fs.lstatSync(markerPath);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error('ECharts vendor marker must be a regular file');
  const marker = JSON.parse(fs.readFileSync(markerPath, 'utf8'));
  const valid = marker &&
    marker.schema === ECHARTS_VENDOR_SCHEMA &&
    marker.version === '1.0.0' && marker.enabled === true &&
    marker.vendor === 'Apache ECharts' && marker.package === 'echarts' &&
    marker.package_version === '6.1.0' && marker.license === 'Apache-2.0' &&
    marker.upstream_repository === 'apache/echarts' && SHA_RE.test(String(marker.upstream_commit || '')) &&
    marker.distribution_path === 'dist/echarts.min.js' && SHA_RE.test(String(marker.git_blob_sha1 || '')) &&
    Number.isInteger(marker.byte_size) && marker.byte_size > 0 &&
    marker.delivery === 'LOCAL_ONLY' && marker.runtime_network_required === false &&
    marker.external_cdn_required === false && marker.cost_class === 'FREE_ONLY';
  if (!valid) throw new Error('ECharts vendor marker is invalid');
  return Object.freeze({ enabled: true, marker: Object.freeze({ ...marker }) });
}

function echartsRawUrl(marker) {
  return `https://raw.githubusercontent.com/${marker.upstream_repository}/${marker.upstream_commit}/${marker.distribution_path}`;
}

function fetchEchartsVendorBytes(marker) {
  const url = echartsRawUrl(marker);
  const bytes = execFileSync('curl', [
    '--fail', '--silent', '--show-error', '--location',
    '--proto', '=https', '--tlsv1.2', '--max-time', '45', url
  ], { encoding: 'buffer', maxBuffer: Math.max(marker.byte_size * 2, 4 * 1024 * 1024) });
  if (bytes.length !== marker.byte_size) throw new Error('ECharts vendor byte size mismatch');
  if (gitBlobSha1(bytes) !== marker.git_blob_sha1) throw new Error('ECharts vendor Git blob hash mismatch');
  return bytes;
}

function localEchartsScriptTag(marker, vendorBytes) {
  if (!Buffer.isBuffer(vendorBytes) || vendorBytes.length !== marker.byte_size) {
    throw new Error('ECharts vendor bytes are invalid');
  }
  if (gitBlobSha1(vendorBytes) !== marker.git_blob_sha1) throw new Error('ECharts vendor Git blob hash mismatch');
  const source = vendorBytes.toString('utf8').replace(/<\/script/gi, '<\\/script');
  return `<script data-prh-vendor="apache-echarts" data-version="${marker.package_version}" data-delivery="LOCAL_ONLY">\n${source}\n</script>`;
}

function injectEchartsVendor(sourceFiles, vendorConfig, fetcher = fetchEchartsVendorBytes) {
  if (!vendorConfig.enabled) return { files: sourceFiles, metadata: null };
  const targetIndex = sourceFiles.findIndex((item) => item.path === ECHARTS_TARGET_HTML);
  if (targetIndex < 0) throw new Error(`${ECHARTS_TARGET_HTML} is required when ECharts vendor is enabled`);
  const target = sourceFiles[targetIndex];
  const html = target.bytes.toString('utf8');
  const placeholderCount = html.split(ECHARTS_VENDOR_PLACEHOLDER).length - 1;
  const headCloseCount = (html.match(/<\/head>/gi) || []).length;
  if (placeholderCount > 1) throw new Error('ECharts vendor placeholder must occur at most once');
  if (placeholderCount === 0 && headCloseCount !== 1) throw new Error('ECharts vendor injection requires exactly one head close tag');
  const vendorBytes = fetcher(vendorConfig.marker);
  const tag = localEchartsScriptTag(vendorConfig.marker, vendorBytes);
  const injectedHtml = placeholderCount === 1
    ? html.replace(ECHARTS_VENDOR_PLACEHOLDER, tag)
    : html.replace(/<\/head>/i, `${tag}\n</head>`);
  const injectedBytes = Buffer.from(injectedHtml, 'utf8');
  const injected = {
    path: target.path,
    sha256: sha256(injectedBytes),
    size: injectedBytes.length,
    bytes: injectedBytes
  };
  const files = sourceFiles.slice();
  files[targetIndex] = injected;
  return {
    files,
    metadata: Object.freeze({
      schema: vendorConfig.marker.schema,
      version: vendorConfig.marker.version,
      package: vendorConfig.marker.package,
      packageVersion: vendorConfig.marker.package_version,
      upstreamCommit: vendorConfig.marker.upstream_commit,
      gitBlobSha1: vendorConfig.marker.git_blob_sha1,
      upstreamByteSize: vendorConfig.marker.byte_size,
      delivery: vendorConfig.marker.delivery,
      runtimeNetworkRequired: false,
      externalCdnRequired: false,
      targetHtml: ECHARTS_TARGET_HTML
    })
  };
}

function buildCandidate({ sourceRoot, repositoryRoot = sourceRoot, outRoot, candidateSha, vendorFetcher = fetchEchartsVendorBytes }) {
  if (!SHA_RE.test(String(candidateSha || ''))) throw new Error('candidate SHA must be exactly 40 lowercase hex characters');
  const source = path.resolve(sourceRoot);
  const repository = path.resolve(repositoryRoot);
  const out = path.resolve(outRoot);
  const filesRoot = path.join(out, 'files');
  if (!fs.existsSync(repository) || !fs.statSync(repository).isDirectory()) {
    throw new Error('repository root must be an existing directory');
  }
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(filesRoot, { recursive: true });

  const names = listDeployFiles(source);
  const originalSourceFiles = sourceFileDescriptors(source, names);
  const vendorConfig = echartsVendorConfig(source);
  const vendorResult = injectEchartsVendor(originalSourceFiles, vendorConfig, vendorFetcher);
  const sourceFiles = vendorResult.files;
  const runtimeConfig = runtimeBundleConfig(source);
  const runtimeBundle = runtimeConfig.enabled
    ? descriptorFromGenerated(GENERATED_RUNTIME_BUNDLE, buildRuntimeBundleSource(repository))
    : null;
  const identityFiles = runtimeBundle
    ? [...sourceFiles, runtimeBundle].sort((a, b) => a.path.localeCompare(b.path))
    : sourceFiles;
  const sourceTreeHash = stableFileSetHash(identityFiles);
  const buildInfoBytes = Buffer.from(buildInfoSource(candidateSha, sourceTreeHash), 'utf8');
  const generatedFile = {
    path: GENERATED_BUILD_INFO,
    sha256: sha256(buildInfoBytes),
    size: buildInfoBytes.length,
    bytes: buildInfoBytes
  };
  const allFiles = [...sourceFiles, ...(runtimeBundle ? [runtimeBundle] : []), generatedFile]
    .sort((a, b) => a.path.localeCompare(b.path));

  allFiles.forEach((item) => fs.writeFileSync(path.join(filesRoot, item.path), item.bytes));
  const manifestFiles = allFiles.map(({ path: filePath, sha256: digest, size }) => ({ path: filePath, sha256: digest, size }));
  const manifest = {
    schemaVersion: 2,
    policyVersion: POLICY_VERSION,
    buildInfoSchemaVersion: BUILD_INFO_SCHEMA_VERSION,
    candidateSha,
    sourceTreeHash,
    generatedBuildInfo: GENERATED_BUILD_INFO,
    fileCount: manifestFiles.length,
    files: manifestFiles,
    artifactHash: stableFileSetHash(manifestFiles)
  };
  if (runtimeBundle) {
    manifest.generatedRuntimeBundle = GENERATED_RUNTIME_BUNDLE;
    manifest.runtimeBundleMarker = runtimeConfig.marker;
  }
  if (vendorResult.metadata) manifest.echartsVendor = vendorResult.metadata;
  fs.writeFileSync(path.join(out, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  return manifest;
}

function verifyCandidate(candidateRoot, expectedRoot, expectedSha) {
  const actualManifestPath = path.join(candidateRoot, 'manifest.json');
  const expectedManifestPath = path.join(expectedRoot, 'manifest.json');
  const actual = JSON.parse(fs.readFileSync(actualManifestPath, 'utf8'));
  const expected = JSON.parse(fs.readFileSync(expectedManifestPath, 'utf8'));
  if (actual.candidateSha !== expectedSha || expected.candidateSha !== expectedSha) throw new Error('candidate SHA binding mismatch');
  if (!SHA_RE.test(actual.candidateSha) || !/^[0-9a-f]{64}$/.test(actual.sourceTreeHash || '')) throw new Error('candidate build identity is invalid');
  if (actual.generatedRuntimeBundle != null && actual.generatedRuntimeBundle !== GENERATED_RUNTIME_BUNDLE) {
    throw new Error('canonical runtime bundle manifest binding invalid');
  }
  if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error('candidate manifest differs from trusted reconstruction');

  const actualFilesRoot = path.join(candidateRoot, 'files');
  const expectedFilesRoot = path.join(expectedRoot, 'files');
  const actualNames = fs.readdirSync(actualFilesRoot).sort();
  const expectedNames = fs.readdirSync(expectedFilesRoot).sort();
  if (JSON.stringify(actualNames) !== JSON.stringify(expectedNames)) throw new Error('candidate file set differs from trusted reconstruction');
  expected.files.forEach((item) => {
    const actualPath = path.join(actualFilesRoot, item.path);
    const actualStat = fs.lstatSync(actualPath);
    if (!actualStat.isFile() || actualStat.isSymbolicLink()) throw new Error(`promoted candidate file must be a regular file: ${item.path}`);
    const actualBytes = fs.readFileSync(actualPath);
    const expectedBytes = fs.readFileSync(path.join(expectedFilesRoot, item.path));
    if (!actualBytes.equals(expectedBytes)) throw new Error(`candidate file differs from trusted reconstruction: ${item.path}`);
    if (sha256(actualBytes) !== item.sha256) throw new Error(`candidate file hash mismatch: ${item.path}`);
  });
  return {
    candidateSha: actual.candidateSha,
    sourceTreeHash: actual.sourceTreeHash,
    artifactHash: actual.artifactHash,
    fileCount: actual.fileCount,
    generatedRuntimeBundle: actual.generatedRuntimeBundle || null,
    echartsVendor: actual.echartsVendor || null
  };
}

if (require.main === module) {
  const args = parseArgs(process.argv);
  if (args.verify) {
    const result = verifyCandidate(path.resolve(args.verify), path.resolve(args.expected), args.sha);
    console.log('apps-script-candidate: VERIFIED', result);
  } else {
    const manifest = buildCandidate({
      sourceRoot: args.source,
      repositoryRoot: args['repository-root'] || args.source,
      outRoot: args.out,
      candidateSha: args.sha
    });
    console.log('apps-script-candidate: BUILT', {
      candidateSha: manifest.candidateSha,
      sourceTreeHash: manifest.sourceTreeHash,
      artifactHash: manifest.artifactHash,
      fileCount: manifest.fileCount,
      generatedRuntimeBundle: manifest.generatedRuntimeBundle || null,
      echartsVendor: manifest.echartsVendor || null
    });
  }
}

